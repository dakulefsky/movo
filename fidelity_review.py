def apply_review(handbooks,sources):
 for h in handbooks:
  for ent in h['entries']:
   for block in ent['blocks']:
    key=(ent['id'],block['id'])
    if key in REPLACEMENTS:block['paragraphs']=[REPLACEMENTS[key]]
    block['paragraphs']=[_trim(p) for p in block['paragraphs']]
    if key==('olah','service'):block['paragraphs']=[p.replace('העולה קדשי קדשים.','עולת בהמה קדשי קדשים.') for p in block['paragraphs']]
